static int16
FindVoiceIn(const char *name, const char **names, int count)
{
	if(name == nil || name[0] == '\0')
		return VOICE_UNK;
	for(int i = 0; i < count; i++)
		if(strcmp(name, names[i]) == 0)
			return (int16)i;
	return VOICE_UNK;
}

// CAEPedSpeechAudioEntity::GetAudioPedType, 0x4E3C60.
eAudioPedType
CPedVoice::GetAudioPedType(const char *name)
{
	if(name == nil)
		return PED_TYPE_UNK;
	if(strcmp(name, "PED_TYPE_GEN") == 0)    return PED_TYPE_GEN;
	if(strcmp(name, "PED_TYPE_EMG") == 0)    return PED_TYPE_EMG;
	if(strcmp(name, "PED_TYPE_PLAYER") == 0) return PED_TYPE_PLAYER;
	if(strcmp(name, "PED_TYPE_GANG") == 0)   return PED_TYPE_GANG;
	if(strcmp(name, "PED_TYPE_GFD") == 0)    return PED_TYPE_GFD;
	if(strcmp(name, "PED_TYPE_SPC") == 0)    return PED_TYPE_SPC;
	return PED_TYPE_UNK;
}

// CAEPedSpeechAudioEntity::GetVoice, 0x4E3CD0. A voice name only means
// something inside its own set, so the set decides which table to read.
int16
CPedVoice::GetVoice(const char *name, eAudioPedType type)
{
	switch(type){
	case PED_TYPE_GEN:    return FindVoiceIn(name, s_aGenVoices, ARRAY_SIZE(s_aGenVoices));
	case PED_TYPE_EMG:    return FindVoiceIn(name, s_aEmgVoices, ARRAY_SIZE(s_aEmgVoices));
	case PED_TYPE_PLAYER: return FindVoiceIn(name, s_aPlyVoices, ARRAY_SIZE(s_aPlyVoices));
	case PED_TYPE_GANG:   return FindVoiceIn(name, s_aGngVoices, ARRAY_SIZE(s_aGngVoices));
	case PED_TYPE_GFD:    return FindVoiceIn(name, s_aGfdVoices, ARRAY_SIZE(s_aGfdVoices));
	default:              return VOICE_UNK;
	}
}
